import { ArrowUpRight, ShieldCheck, Sparkles } from "lucide-react";
import type { AuraAnalysis, AuraStrategy } from "@/lib/aura/types";

function riskClass(risk: string): string {
  const value = risk.toLowerCase();
  if (value.includes("low")) return "risk-low";
  if (value.includes("high")) return "risk-high";
  return "risk-medium";
}

function StrategyRow({ strategy, index }: { strategy: AuraStrategy; index: number }) {
  return (
    <article className="strategy-row">
      <div className="strategy-number">{String(index + 1).padStart(2, "0")}</div>
      <div className="strategy-main">
        <div className="strategy-title-line"><h3>{strategy.name}</h3><span className={`risk-label ${riskClass(strategy.risk)}`}>{strategy.risk} risk</span></div>
        <p>{strategy.description ?? "AURA returned this opportunity for further review."}</p>
        <div className="strategy-tags">{strategy.tokens && <span>{strategy.tokens}</span>}{strategy.network && <span>{strategy.network}</span>}{strategy.protocol && <span>{strategy.protocol}</span>}</div>
      </div>
      <div className="strategy-value"><span>{strategy.apy === undefined ? "AURA" : `${strategy.apy.toFixed(2)}%`}</span><small>{strategy.apy === undefined ? "recommended" : "estimated APY"}</small></div>
    </article>
  );
}

export function StrategyResults({ analysis }: { analysis: AuraAnalysis }) {
  return (
    <section className="strategy-section standalone-section" aria-labelledby="strategy-title">
      <div className="section-heading strategy-heading">
        <div><p className="section-index">02 / Next best action</p><h2 id="strategy-title">What could be useful next.</h2></div>
        <div className="intelligence-source"><Sparkles size={15} /> Generated by AURA</div>
      </div>
      <div className="insight-banner"><ShieldCheck size={22} /><p><strong>AuraLens interpretation.</strong> These are contextual suggestions from AURA, not financial advice. Review protocols and risks before acting.</p></div>
      <div className="strategy-list">
        {analysis.strategies.map((strategy, index) => <StrategyRow key={`${strategy.name}-${index}`} strategy={strategy} index={index} />)}
        {analysis.strategies.length === 0 && <div className="strategy-empty">AURA returned wallet context but no strategies for this address.</div>}
      </div>
      <a className="source-link" href="https://aura.adex.network" target="_blank" rel="noreferrer">Intelligence supplied by AURA <ArrowUpRight size={15} /></a>
    </section>
  );
}
