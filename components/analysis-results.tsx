import { ArrowUpRight, ShieldCheck, Sparkles } from "lucide-react";
import type { AuraAnalysis, AuraStrategy } from "@/lib/aura/types";
import { formatCurrency, formatTokenBalance } from "@/lib/formatters";
import { DeveloperPanel } from "@/components/developer-panel";

function riskClass(risk: string): string {
  const value = risk.toLowerCase();
  if (value.includes("low")) return "risk-low";
  if (value.includes("high")) return "risk-high";
  return "risk-medium";
}

function StrategyRow({ strategy, index }: { strategy: AuraStrategy; index: number }) {
  return (
    <article className="strategy-row">
      <div className="strategy-number">{String(index + 1).padStart(2, "0")}</div>
      <div className="strategy-main">
        <div className="strategy-title-line">
          <h3>{strategy.name}</h3>
          <span className={`risk-label ${riskClass(strategy.risk)}`}>{strategy.risk} risk</span>
        </div>
        <p>{strategy.description ?? "AURA returned this opportunity for further review."}</p>
        <div className="strategy-tags">
          {strategy.tokens && <span>{strategy.tokens}</span>}
          {strategy.network && <span>{strategy.network}</span>}
          {strategy.protocol && <span>{strategy.protocol}</span>}
        </div>
      </div>
      <div className="strategy-value">
        <span>{strategy.apy === undefined ? "AURA" : `${strategy.apy.toFixed(2)}%`}</span>
        <small>{strategy.apy === undefined ? "recommended" : "estimated APY"}</small>
      </div>
    </article>
  );
}

export function AnalysisResults({ analysis }: { analysis: AuraAnalysis }) {
  const lowBalance = analysis.totalBalanceUSD < 10;

  return (
    <div className="results-shell">
      <section className="overview-section" aria-labelledby="overview-title">
        <div className="section-heading">
          <div>
            <p className="section-index">01 / Wallet context</p>
            <h2 id="overview-title">What the app knows.</h2>
          </div>
          <span className="api-stamp">AURA {analysis.version ?? "API"}</span>
        </div>

        <div className="overview-grid">
          <div className="balance-block">
            <span>Estimated portfolio</span>
            <strong>{formatCurrency(analysis.totalBalanceUSD)}</strong>
            <p>{lowBalance ? "Low balance detected. AURA is prioritizing foundational next steps." : "Portfolio context is informing the opportunities below."}</p>
          </div>
          <dl className="metrics-grid">
            <div><dt>Networks</dt><dd>{analysis.networkCount}</dd></div>
            <div><dt>Assets</dt><dd>{analysis.assetCount}</dd></div>
            <div><dt>Strategies</dt><dd>{analysis.strategies.length}</dd></div>
            <div><dt>Source</dt><dd>{analysis.cached ? "Cached" : "Live"}</dd></div>
          </dl>
        </div>

        <div className="asset-table" role="table" aria-label="Wallet assets">
          <div className="asset-head" role="row">
            <span>Asset</span><span>Network</span><span>Balance</span><span>USD value</span>
          </div>
          {analysis.portfolio.flatMap((entry) => entry.tokens.map((token) => (
            <div className="asset-row" role="row" key={`${entry.network.chainId}-${token.address ?? token.symbol}`}>
              <span><i>{token.symbol.slice(0, 1)}</i><b>{token.symbol}</b></span>
              <span>{entry.network.name}</span>
              <span>{formatTokenBalance(token.balance)}</span>
              <span>{formatCurrency(token.balanceUSD)}</span>
            </div>
          )))}
          {analysis.assetCount === 0 && <div className="table-empty">No on-chain assets were returned for this wallet.</div>}
        </div>
      </section>

      <section className="strategy-section" aria-labelledby="strategy-title">
        <div className="section-heading strategy-heading">
          <div>
            <p className="section-index">02 / Next best action</p>
            <h2 id="strategy-title">What could be useful next.</h2>
          </div>
          <div className="intelligence-source"><Sparkles size={15} /> Generated by AURA</div>
        </div>
        <div className="insight-banner">
          <ShieldCheck size={22} />
          <p><strong>AuraLens interpretation.</strong> These are contextual suggestions from AURA, not financial advice. Review protocols and risks before acting.</p>
        </div>
        <div className="strategy-list">
          {analysis.strategies.map((strategy, index) => <StrategyRow key={`${strategy.name}-${index}`} strategy={strategy} index={index} />)}
          {analysis.strategies.length === 0 && <div className="strategy-empty">AURA returned wallet context but no strategies for this address.</div>}
        </div>
        <a className="source-link" href="https://aura.adex.network" target="_blank" rel="noreferrer">
          Intelligence supplied by AURA <ArrowUpRight size={15} />
        </a>
      </section>

      <DeveloperPanel analysis={analysis} />
    </div>
  );
}
